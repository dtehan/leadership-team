#!/usr/bin/env python3
"""Regenerate the progressive-loading indexes under accounts/{account}/company/.

Every directory under company/ gets an index.md. Text above the marker line is
hand/LLM-written (account brief, area notes) and is preserved. Everything below
the marker is generated from the front-matter of the documents in that folder.

Document front-matter (all optional except summary):

    ---
    title: FY2024 Form 10-K — key financials
    summary: One or two lines — what is in here and why it matters.
    tags: [revenue, margin, medical-cost-ratio]
    as_of: 2025-02-13
    source: https://www.sec.gov/...
    confidence: high | medium | low
    roles: [cfo, leader]        # who should load it by default
    load: always | on-demand    # profile dossiers only; default on-demand
    ---

Usage:
    python3 scripts/build_index.py {account}            # rebuild all indexes for accounts/{account}/company
    python3 scripts/build_index.py {account} --check    # report problems, change nothing
"""
import re
import sys
from pathlib import Path

ROOT = None  # set in main(): accounts/{slug}/company
MARKER = "<!-- AUTO-INDEX: generated by scripts/build_index.py — do not edit below this line -->"
SKIP_FILES = {"index.md", "readme.md", "gaps.md"}
SKIP_DIRS = {"sources", "raw"}


def parse_front_matter(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    meta = {}
    if not m:
        return meta
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not kv:
            continue
        key, val = kv.group(1), kv.group(2).strip()
        if val.startswith("[") and val.endswith("]"):
            meta[key] = [v.strip().strip("'\"") for v in val[1:-1].split(",") if v.strip()]
        else:
            meta[key] = val.strip("'\"")
    return meta


def cell(value):
    if isinstance(value, list):
        value = ", ".join(value)
    return (value or "").replace("|", "\\|").replace("\n", " ")


def child_dirs(d):
    return sorted(p for p in d.iterdir()
                  if p.is_dir() and not p.name.startswith((".", "_")) and p.name not in SKIP_DIRS)


def docs_in(d):
    return sorted(p for p in d.glob("*.md") if p.name.lower() not in SKIP_FILES)


def build_dir(d, check, problems):
    rows_dirs, rows_docs = [], []
    for sub in child_dirs(d):
        meta = parse_front_matter(sub / "index.md") if (sub / "index.md").exists() else {}
        if "person" in meta:  # a role dossier
            desc = f"{meta['person']} — {meta.get('title', '')}".strip(" —")
        else:
            desc = meta.get("description", "")
        rows_dirs.append(f"| [{sub.name}/]({sub.name}/index.md) | {cell(desc)} |")

    for doc in docs_in(d):
        meta = parse_front_matter(doc)
        if not meta.get("summary"):
            problems.append(f"{doc.relative_to(ROOT.parent)}: missing front-matter 'summary'")
        rows_docs.append(
            f"| [{doc.name}]({doc.name}) | {cell(meta.get('summary'))} | {cell(meta.get('tags'))} "
            f"| {cell(meta.get('as_of'))} | {cell(meta.get('confidence'))} "
            f"| {cell(meta.get('roles'))} | {cell(meta.get('load', 'on-demand'))} |"
        )

    out = [MARKER, ""]
    if rows_dirs:
        out += ["## Sections", "", "| Section | About |", "|---|---|", *rows_dirs, ""]
    if rows_docs:
        out += ["## Documents", "",
                "| Document | Summary | Tags | As of | Confidence | Roles | Load |",
                "|---|---|---|---|---|---|---|", *rows_docs, ""]
    if not rows_dirs and not rows_docs:
        out += ["_No documents yet._", ""]

    idx = d / "index.md"
    head = ""
    if idx.exists():
        existing = idx.read_text(encoding="utf-8")
        head = existing.split(MARKER)[0].rstrip() + "\n\n" if existing.strip() else ""
    if not head:
        head = f"---\ndescription: TODO one line about {d.name}\n---\n\n# {d.name.title()}\n\n"
    if d != ROOT and head.lstrip().startswith("---") is False:
        problems.append(f"{idx.relative_to(ROOT.parent)}: no front-matter 'description'")
    if not check:
        idx.write_text(head + "\n".join(out), encoding="utf-8")


def walk(d, check, problems):
    for sub in child_dirs(d):
        walk(sub, check, problems)
    build_dir(d, check, problems)


def main():
    global ROOT
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    ROOT = Path(__file__).resolve().parent.parent / "accounts" / args[0] / "company"
    check = "--check" in sys.argv
    if not ROOT.exists():
        sys.exit(f"{ROOT} not found")
    problems = []
    walk(ROOT, check, problems)
    for p in problems:
        print("WARN", p)
    print(("Checked" if check else "Rebuilt") + f" indexes under {ROOT.relative_to(ROOT.parent)}/"
          + (f" — {len(problems)} warning(s)" if problems else ""))
    sys.exit(1 if (check and problems) else 0)


if __name__ == "__main__":
    main()
